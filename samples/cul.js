let a = 10;
let b = 3;

// 足し算（加算）
console.log(a + b);    // 13

// 引き算（減算）
console.log(a - b);    // 7

// 掛け算（乗算）
console.log(a * b);    // 30

// 割り算（除算）
console.log(a / b);    // 3.333...

// 余り（剰余）
console.log(a % b);    // 1（10 ÷ 3 の余り）

// 累乗（指数）
console.log(a ** b);   // 1000（10の3乗）

// 単項プラス（正数を明示）
let x = "5";
console.log(+x);       // 5（文字列 → 数値に変換される）

// 単項マイナス（符号を反転）
console.log(-a);       // -10
